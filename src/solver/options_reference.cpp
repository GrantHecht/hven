// hven/solver/options_reference.h: the generated options reference, and the range text the
// registry's renderers share. The per-engine rows
// (ipm_option_info, sqp_option_info) are built in src/ipm/ipm_options.cpp and
// src/sqp/sqp_options.cpp, next to the tables they walk; this file reads only their result.

#include <cstddef>
#include <ostream>
#include <string>
#include <string_view>
#include <vector>

#include <fmt/format.h>

