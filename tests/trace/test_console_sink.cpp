//       notice, warning, detail line, the footer's five lines).
//   (b) GOLDENS rendered from those two real solves, inline, with colour off, the legend on and
//       the wall-clock line off. They were generated by running the sink and read against the
//       spec's formats (column alignment, `-` for a missing value, the condensed codes).
