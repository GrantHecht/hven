// --- capture ----------------------------------------------------------------

/// A `FILE *` the sink writes to and the test reads back whole.
class Capture {
  public:
    Capture() : file_(std::tmpfile()) {}
    ~Capture() {
        if (file_ != nullptr) {
            std::fclose(file_);
        }
    }
    Capture(const Capture &) = delete;
    Capture &operator=(const Capture &) = delete;

    std::FILE *file() const { return file_; }

    std::string text() const {
        std::fflush(file_);
        std::fseek(file_, 0, SEEK_END);
        const long end = std::ftell(file_);
        std::string out(static_cast<std::size_t>(end), '\0');
        std::fseek(file_, 0, SEEK_SET);
        const std::size_t got = std::fread(out.data(), 1, out.size(), file_);
        out.resize(got);
        std::fseek(file_, 0, SEEK_END);
        return out;
    }

  private:
    std::FILE *file_;
};

ConsoleTraceSink::Format fmt_of(Verbosity v, ConsoleColor color = ConsoleColor::kNever,
                                bool legend = true, bool timing = false) {
    return ConsoleTraceSink::Format{
        .verbosity = v, .color = color, .legend = legend, .timing = timing};
}

std::vector<std::string> lines_of(const std::string &text) {
    std::vector<std::string> out;
    std::size_t begin = 0;
    while (begin < text.size()) {
        const std::size_t nl = text.find('\n', begin);
        if (nl == std::string::npos) {
            out.push_back(text.substr(begin));
            break;
        }
        out.push_back(text.substr(begin, nl - begin));
        begin = nl + 1;
    }
    return out;
}

// --- line kinds --------------------------------------------------------------

enum class Kind {
    kHeader,     // "hven <version> -- <engine>"
    kProblem,    // "problem    ..."
    kEngine,     // "engine     ..."
    kTolerances, // "tolerances ..."
    kLegend,     // "legend  ..." and its continuation lines
    kColumns,    // " iter t ..."
    kRow,        // one iteration row
    kNotice,     // "      - ..."
    kWarning,    // "      ! ..."
    kDetail,     // "      . ..."
    kPhase,      // "phase k: ..."
    kExit,       // the footer's five lines and the optional time line
    kIterations,
    kObjective,
    kDiagnostics,
    kCounters,
    kTime,
    kOther,
};

bool starts_with(const std::string &s, std::string_view p) { return s.rfind(p, 0) == 0; }

Kind classify(const std::string &l) {
    if (starts_with(l, "hven ")) {
        return Kind::kHeader;
    }
    if (starts_with(l, "problem    ")) {
        return Kind::kProblem;
    }
    if (starts_with(l, "engine     ")) {
        return Kind::kEngine;
    }
    if (starts_with(l, "tolerances ")) {
        return Kind::kTolerances;
    }
    if (starts_with(l, "legend  ") || starts_with(l, "        ")) {
        return Kind::kLegend;
    }
    if (starts_with(l, " iter t")) {
        return Kind::kColumns;
    }
    if (starts_with(l, "      - ")) {
        return Kind::kNotice;
    }
    if (starts_with(l, "      ! ")) {
        return Kind::kWarning;
    }
    if (starts_with(l, "      . ")) {
        return Kind::kDetail;
    }
    if (starts_with(l, "phase ")) {
        return Kind::kPhase;
    }
    if (starts_with(l, "exit ")) {
        return Kind::kExit;
    }
    if (starts_with(l, "iterations ")) {
        return Kind::kIterations;
    }
    if (starts_with(l, "objective ")) {
        return Kind::kObjective;
    }
    if (starts_with(l, "diagnostics ")) {
        return Kind::kDiagnostics;
    }
    if (starts_with(l, "counters ")) {
        return Kind::kCounters;
    }
    if (starts_with(l, "time ")) {
        return Kind::kTime;
    }
    // A row: `{iter:>5} {tier} ...`.
    if (l.size() > 8 && l[5] == ' ' && l[7] == ' ' &&
        std::string_view("BISWER").find(l[6]) != std::string_view::npos &&
        std::isdigit(static_cast<unsigned char>(l[4])) != 0) {
        return Kind::kRow;
    }
    return Kind::kOther;
}

std::map<Kind, Index> census_of(const std::string &text) {
    std::map<Kind, Index> out;
    for (const std::string &l : lines_of(text)) {
        ++out[classify(l)];
    }
    return out;
}

Index count(const std::map<Kind, Index> &c, Kind k) {
    const auto it = c.find(k);
    return it == c.end() ? Index{0} : it->second;
}

// --- real solves ---------------------------------------------------------------

/// The process-global initialization notice fires once per process; a throwaway solve takes it
/// out of every transcript below.
void warm_process() {
    static std::once_flag once;
    std::call_once(once, [] {
        Problem problem(std::make_shared<Hs071Problem>());
        IpmSolver solver{IpmOptions{}};
        (void)solver.solve(problem, hs071_start());
    });
}

std::string ipm_transcript(const ConsoleTraceSink::Format &format, Index *iterations = nullptr) {
    warm_process();
    Capture capture;
    ConsoleTraceSink sink(format, capture.file());
    Problem problem(std::make_shared<Hs071Problem>());
    IpmSolver solver{IpmOptions{}};
    solver.attach_trace(&sink);
    const IpmResult result = solver.solve(problem, hs071_start());
    EXPECT_EQ(result.status, SolveStatus::kOptimal);
    if (iterations != nullptr) {
        *iterations = result.iterations;
    }
    return capture.text();
}

std::string sqp_transcript(const ConsoleTraceSink::Format &format, Index *iterations = nullptr) {
    warm_process();
    Capture capture;
    ConsoleTraceSink sink(format, capture.file());
    Problem problem(std::make_shared<Hs071Problem>());
    SqpSolver solver{SqpOptions{}};
    solver.attach_trace(&sink);
    const SqpResult result = solver.solve(problem, hs071_start());
    EXPECT_EQ(result.status, SolveStatus::kOptimal);
    if (iterations != nullptr) {
        *iterations = result.iterations;
    }
    return capture.text();
}

