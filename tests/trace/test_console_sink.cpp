struct Expected {
    Index header, problem, engine, tolerances;                // the four header lines
    Index exit, iterations, objective, diagnostics, counters; // the footer's lines
    bool legend, columns, rows, detail;
};

void expect_rung(const std::string &text, const Expected &e, Index row_count) {
    const std::map<Kind, Index> c = census_of(text);
    EXPECT_EQ(count(c, Kind::kHeader), e.header) << text;
    EXPECT_EQ(count(c, Kind::kProblem), e.problem);
    EXPECT_EQ(count(c, Kind::kEngine), e.engine);
    EXPECT_EQ(count(c, Kind::kTolerances), e.tolerances);
    EXPECT_EQ(count(c, Kind::kExit), e.exit);
    EXPECT_EQ(count(c, Kind::kIterations), e.iterations);
    EXPECT_EQ(count(c, Kind::kObjective), e.objective);
    EXPECT_EQ(count(c, Kind::kDiagnostics), e.diagnostics);
    EXPECT_EQ(count(c, Kind::kCounters), e.counters);
    EXPECT_EQ(count(c, Kind::kLegend) > 0, e.legend) << "legend";
    EXPECT_EQ(count(c, Kind::kColumns) > 0, e.columns) << "column header";
    EXPECT_EQ(count(c, Kind::kRow), e.rows ? row_count : Index{0}) << "rows";
    EXPECT_EQ(count(c, Kind::kDetail) > 0, e.detail) << "detail lines";
    EXPECT_EQ(count(c, Kind::kTime), 0) << "timing is off";
    EXPECT_EQ(count(c, Kind::kOther), 0) << "no unclassified line in:\n" << text;
    // A clean solve raises no warning and prints no phase line (one phase).
    EXPECT_EQ(count(c, Kind::kWarning), 0);
    EXPECT_EQ(count(c, Kind::kPhase), 0);
}

TEST(ConsoleLadder, AnInteriorPointSolveClimbsOneRungAtATime) {
    Index iterations = 0;
    const std::string iterations_text = ipm_transcript(fmt_of(Verbosity::kIterations), &iterations);
    ASSERT_GT(iterations, 1);

    // kSilent: nothing at all.
    EXPECT_EQ(ipm_transcript(fmt_of(Verbosity::kSilent)), "");
    // kWarnings: the exit line, and nothing else on a solve that raises no warning.
    expect_rung(ipm_transcript(fmt_of(Verbosity::kWarnings)),
                {0, 0, 0, 0, 1, 0, 0, 0, 0, false, false, false, false}, iterations);
    // kSummary: + the header block and the rest of the footer.
    expect_rung(ipm_transcript(fmt_of(Verbosity::kSummary)),
                {1, 1, 1, 1, 1, 1, 1, 1, 1, false, false, false, false}, iterations);
    // kIterations: + the legend, the column header and every row.
    expect_rung(iterations_text, {1, 1, 1, 1, 1, 1, 1, 1, 1, true, true, true, false}, iterations);
    // kDetail: + the KKT-analysis and phase-exit lines.
    const std::string detail = ipm_transcript(fmt_of(Verbosity::kDetail));
    expect_rung(detail, {1, 1, 1, 1, 1, 1, 1, 1, 1, true, true, true, true}, iterations);
    EXPECT_NE(detail.find("      . KKT analysis: dim "), std::string::npos);
    EXPECT_NE(detail.find("      . phase 0 exit: stop "), std::string::npos);
}

TEST(ConsoleLadder, ASqpSolveClimbsOneRungAtATime) {
    Index iterations = 0;
    const std::string iterations_text = sqp_transcript(fmt_of(Verbosity::kIterations), &iterations);
    ASSERT_GT(iterations, 1);
    // The SQP's depth-0 rows are `iterations + 1`: row 0 is the start point.
    const Index rows = iterations + 1;

    EXPECT_EQ(sqp_transcript(fmt_of(Verbosity::kSilent)), "");
    expect_rung(sqp_transcript(fmt_of(Verbosity::kWarnings)),
                {0, 0, 0, 0, 1, 0, 0, 0, 0, false, false, false, false}, rows);
    expect_rung(sqp_transcript(fmt_of(Verbosity::kSummary)),
                {1, 1, 1, 1, 1, 1, 1, 1, 1, false, false, false, false}, rows);
    expect_rung(iterations_text, {1, 1, 1, 1, 1, 1, 1, 1, 1, true, true, true, false}, rows);
    const std::string detail = sqp_transcript(fmt_of(Verbosity::kDetail));
    expect_rung(detail, {1, 1, 1, 1, 1, 1, 1, 1, 1, true, true, true, true}, rows);
    EXPECT_NE(detail.find("      . qp.mode "), std::string::npos)
        << "the QP-tier lines belong to the detail rung";
}

TEST(ConsoleLadder, TheLegendFlagSuppressesOnlyTheLegend) {
    const std::string with = ipm_transcript(fmt_of(Verbosity::kIterations));
    const std::string without =
        ipm_transcript(fmt_of(Verbosity::kIterations, ConsoleColor::kNever, /*legend=*/false));
    const std::map<Kind, Index> a = census_of(with);
    const std::map<Kind, Index> b = census_of(without);
    EXPECT_GT(count(a, Kind::kLegend), 0);
    EXPECT_EQ(count(b, Kind::kLegend), 0);
    EXPECT_EQ(count(a, Kind::kRow), count(b, Kind::kRow));
    EXPECT_EQ(count(a, Kind::kColumns), count(b, Kind::kColumns));
}

TEST(ConsoleLadder, TimingAddsExactlyOneInformationalLine) {
    const std::string off = ipm_transcript(fmt_of(Verbosity::kSummary));
    const std::string on =
        ipm_transcript(fmt_of(Verbosity::kSummary, ConsoleColor::kNever, true, /*timing=*/true));
    EXPECT_EQ(count(census_of(off), Kind::kTime), 0);
    EXPECT_EQ(count(census_of(on), Kind::kTime), 1);
    EXPECT_NE(on.find("(informational)\n"), std::string::npos);
}

