TEST(ConsoleColour, NeverEmitsNoEscapeAndAlwaysColoursOnlyTheWarningMarkAndTheExitLine) {
    const IpmCounters counters;
    const auto run = [&](ConsoleColor color) {
        return feed(fmt_of(Verbosity::kDetail, color), [&](TraceSink &s) {
            s.on_solve_begin(ipm_begin());
            s.on_iter(IterTraceEvent{ipm_row(0)});
            s.on_message(message(TraceEngine::kIpm, MessageKind::kStartPointClamped));
            s.on_message(message(TraceEngine::kIpm, MessageKind::kRankDeficiency));
            s.on_iter(IterTraceEvent{ipm_row(1)});
            s.on_ipm_kkt_analysis(IpmKktAnalysisTraceEvent{});
            s.on_solve_end(ipm_end(counters));
        });
    };
    const std::string never = run(ConsoleColor::kNever);
    EXPECT_EQ(never.find('\x1b'), std::string::npos);

    // kAuto on a file (not a terminal) is kNever.
    EXPECT_EQ(run(ConsoleColor::kAuto).find('\x1b'), std::string::npos);

    const std::string always = run(ConsoleColor::kAlways);
    EXPECT_NE(always.find('\x1b'), std::string::npos);
    for (const std::string &l : lines_of(always)) {
        const bool has_escape = l.find('\x1b') != std::string::npos;
        const Kind k = classify(l);
        if (has_escape) {
            // Only the warning's mark and the exit line carry one. The warning's line starts
            // `{'':>5} ` and then the SGR sequence, so classify() by the mark sees the escape.
            EXPECT_TRUE(l.rfind("exit ", 0) == 0 || l.find(" rank deficient") != std::string::npos)
                << "a colour escape on: " << l;
        } else {
            EXPECT_TRUE(k == Kind::kHeader || k == Kind::kProblem || k == Kind::kEngine ||
                        k == Kind::kTolerances || k == Kind::kLegend || k == Kind::kColumns ||
                        k == Kind::kRow || k == Kind::kNotice || k == Kind::kDetail ||
                        k == Kind::kIterations || k == Kind::kObjective ||
                        k == Kind::kDiagnostics || k == Kind::kCounters)
                << l;
        }
    }
    // The warning's TEXT is the same bytes without the colour: stripping the escapes of the
    // coloured transcript gives the plain one.
    std::string stripped;
    for (std::size_t i = 0; i < always.size(); ++i) {
        if (always[i] == '\x1b') {
            while (i < always.size() && always[i] != 'm') {
                ++i;
            }
            continue;
        }
        stripped += always[i];
    }
    EXPECT_EQ(stripped, never);
}

