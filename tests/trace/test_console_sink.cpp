/// A sink that counts every event it is handed and records the order.
struct CountingSink : TraceSink {
    std::vector<std::string> seen;
    // An optional SHARED, ORDERED observation: when `shared` is set every event is also
    // appended to ONE vector as "<tag>:<event>", so the order of delivery is readable.
    std::vector<std::string> *shared = nullptr;
    std::string tag;

    void note(const char *name) {
        seen.push_back(name);
        if (shared != nullptr) {
            shared->push_back(tag + ":" + name);
        }
    }
    void on_ipqp_iter(const IpqpIterTraceEvent &) override { note("ipqp.iter"); }
    void on_ipqp_reg(const IpqpRegTraceEvent &) override { note("ipqp.reg"); }
    void on_ipqp_restart(const IpqpRestartTraceEvent &) override { note("ipqp.restart"); }
    void on_ipqp_route(const IpqpRouteTraceEvent &) override { note("ipqp.route"); }
    void on_ipqp_certify(const IpqpCertifyTraceEvent &) override { note("ipqp.certify"); }
    void on_ipqp_escape(const IpqpEscapeTraceEvent &) override { note("ipqp.escape"); }
    void on_qp_mode(const QpModeTraceEvent &) override { note("qp.mode"); }
    void on_fallback_verdict(const SqpFallbackVerdictTraceEvent &) override {
        note("fallback.verdict");
    }
    void on_solve_begin(const SolveBeginTraceEvent &) override { note("solve.begin"); }
    void on_iter(const IterTraceEvent &) override { note("iter"); }
    void on_message(const MessageTraceEvent &) override { note("message"); }
    void on_solve_end(const SolveEndTraceEvent &) override { note("solve.end"); }
    void on_ipm_phase_begin(const IpmPhaseTraceEvent &) override { note("ipm.phase.begin"); }
    void on_ipm_phase_end(const IpmPhaseTraceEvent &) override { note("ipm.phase.end"); }
    void on_ipm_kkt_analysis(const IpmKktAnalysisTraceEvent &) override {
        note("ipm.kkt_analysis");
    }
    void on_ipm_phase_exit(const IpmPhaseExitTraceEvent &) override { note("ipm.phase.exit"); }
};

TEST(FanOut, ForwardsEveryEventToBothHalvesFirstThenSecond) {
    // ONE SHARED, ORDERED OBSERVATION: the two sinks write into the same vector, tagged, so
    // "first then second" is a property of the sequence rather than of two sequences that happen
    // to agree.
    std::vector<std::string> order;
    CountingSink a;
    CountingSink b;
    a.shared = &order;
    a.tag = "a";
    b.shared = &order;
    b.tag = "b";
    FanOutTraceSink fan(&a, &b);
    const SqpCounters counters;
    const IpmIterate iterate;
    const IpmPhaseReport report;
    const IterationRecord record = sqp_row(0);
    fan.on_ipqp_iter(IpqpIterTraceEvent{});
    fan.on_ipqp_reg(IpqpRegTraceEvent{});
    fan.on_ipqp_restart(IpqpRestartTraceEvent{});
    fan.on_ipqp_route(IpqpRouteTraceEvent{});
    fan.on_ipqp_certify(IpqpCertifyTraceEvent{});
    fan.on_ipqp_escape(IpqpEscapeTraceEvent{});
    fan.on_qp_mode(QpModeTraceEvent{});
    fan.on_fallback_verdict(SqpFallbackVerdictTraceEvent{});
    fan.on_solve_begin(sqp_begin());
    fan.on_iter(IterTraceEvent{record});
    fan.on_message(MessageTraceEvent{});
    fan.on_solve_end(sqp_end(counters));
    fan.on_ipm_phase_begin(IpmPhaseTraceEvent{});
    fan.on_ipm_phase_end(IpmPhaseTraceEvent{});
    fan.on_ipm_kkt_analysis(IpmKktAnalysisTraceEvent{});
    fan.on_ipm_phase_exit(IpmPhaseExitTraceEvent{report, iterate});

    // EVERY virtual is covered: sixteen names, none repeated.
    EXPECT_EQ(a.seen.size(), 16u);
    EXPECT_EQ(a.seen, b.seen);
    EXPECT_EQ(fan.first(), &a);
    EXPECT_EQ(fan.second(), &b);

    // AND EVERY ONE OF THEM REACHED `a` BEFORE `b`: the shared log alternates, each pair naming
    // one event. Reversing the fan-out's delivery order fails here and nowhere else.
    ASSERT_EQ(order.size(), 32u);
    for (std::size_t i = 0; i < a.seen.size(); ++i) {
        EXPECT_EQ(order[2 * i], "a:" + a.seen[i]) << "at event " << i;
        EXPECT_EQ(order[2 * i + 1], "b:" + a.seen[i]) << "at event " << i;
    }
}

TEST(FanOut, ANullHalfIsSkippedRatherThanDereferenced) {
    CountingSink a;
    FanOutTraceSink first_only(&a, nullptr);
    FanOutTraceSink second_only(nullptr, &a);
    FanOutTraceSink neither(nullptr, nullptr);
    const IterationRecord record = sqp_row(0);
    first_only.on_iter(IterTraceEvent{record});
    second_only.on_iter(IterTraceEvent{record});
    neither.on_iter(IterTraceEvent{record});
    EXPECT_EQ(a.seen.size(), 2u);
}

TEST(FanOut, AUserSinkIsNotDisplacedByTheConsole) {
    // The composition the drivers build: the caller's sink FIRST, the console second. What the
    // caller receives from a real solve must be exactly what it receives with no console at all.
    warm_process();
    const auto solve = [](TraceSink &sink) {
        Problem problem(std::make_shared<Hs071Problem>());
        IpmSolver solver{IpmOptions{}};
        solver.attach_trace(&sink);
        return solver.solve(problem, hs071_start());
    };
    CountingSink alone;
    (void)solve(alone);

    CountingSink user;
    Capture capture;
    ConsoleTraceSink console(fmt_of(Verbosity::kIterations), capture.file());
    FanOutTraceSink fan(&user, &console);
    const IpmResult result = solve(fan);
    EXPECT_EQ(user.seen, alone.seen);
    ASSERT_FALSE(user.seen.empty());
    EXPECT_FALSE(capture.text().empty());
    // And the console saw the same solve: one row per `iter` event.
    Index iter_events = 0;
    for (const std::string &s : user.seen) {
        iter_events += (s == "iter") ? 1 : 0;
    }
    EXPECT_EQ(iter_events, result.iterations);
    EXPECT_EQ(count(census_of(capture.text()), Kind::kRow), iter_events);
}

