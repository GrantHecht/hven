#!/usr/bin/env python3
"""M7 W2 M4 -- POST-HOC read-outs over the TWELVE NEUTRALITY traces.

**POST-HOC.**  RULE.md section 6 was pre-registered for the TEN cells of
section 1.1 and for the phase-3 legs that section 8 stopped before they ran.
It was NOT pre-registered for the three neutrality cells of section 1.2.
Everything this script prints is therefore labelled POST-HOC wherever it is
carried, and no verdict of the rule rests on it.  RULE.md is not edited.

What it does, and nothing else:

* it splits each of the twelve flat traces (3 neutrality cells x 4 arms) into
  its per-solve records, using the trace's own `solve` column;
* per solve it applies RULE.md section 6.2's predicate MECHANICALLY, through
  `readouts_m4.py`'s own unedited tail finder (`f0_keys`,
  `maximal_periodic_tail`, PERIOD_CAP 64):
      T1  a maximal exactly-periodic suffix T at some p <= 64 EXISTS
      T2  |T| >= 0.10 * N
      T3  |T| >= 8p
      RECURRENT_TAIL = T1 and T2 and T3
      RECURRENCE_GONE = (not RECURRENT_TAIL) and (sum |dx|_inf over the
                        WHOLE solve > 0)          -- section 6.5
* it writes per-solve slices for the RECURRENT solves of any arm on that cell,
  so that the same solve index can be read under all four arms, and runs
  `read_out()` on each slice for section 6.6's per-solve read-outs;
* it prints the OFF-vs-E comparison the settler asked for and nothing beyond
  what the numbers say.

No solver runs here.
"""

import os
import sys
from collections import OrderedDict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import readouts_m4 as R                  # noqa: E402
import classify_cause_fix1 as cc         # noqa: E402

ARMS = ("off", "E", "L", "L+")
CELLS = ("READING6", "SMBANK", "ZAMB2-8")


def read_flat(path):
    head, cols, rows = [], None, []
    with open(path, errors="replace") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if line.startswith("#"):
                head.append(line)
                continue
            if not line:
                continue
            if cols is None:
                cols = line
                continue
            rows.append(line)
    hdr = {}
    for h in head:
        s = h[1:].strip()
        if "=" in s:
            k, v = s.split("=", 1)
            hdr[k.strip()] = v.strip()
    return head, cols, rows, hdr


def by_solve(rows):
    out = OrderedDict()
    for line in rows:
        k = int(line.split(",", 1)[0])
        out.setdefault(k, []).append(line)
    return out


def typed_rows(cols, lines):
    names = cols.split(",")
    return [dict(zip(names, l.split(","))) for l in lines]


def f0_of(raws):
    return [tuple(cc.bitkey(c, r[c]) for c in cc.F0) for r in raws]


def fnum(t):
    try:
        v = float(t)
    except (TypeError, ValueError):
        return None
    return None if v != v else v


def predicate(raws):
    """RULE.md section 6.2/6.5, applied through readouts_m4's own machinery."""
    n = len(raws)
    keys = f0_of(raws)
    p, t0, nfail = R.maximal_periodic_tail(keys)
    d = {"N": n, "p": p, "t0": t0, "repeat_failures": nfail}
    if p is None:
        d.update(T1=False, tail=0, T2=False, T3=False, recurrent=False)
    else:
        tl = n - t0
        d["tail"] = tl
        d["T1"] = True
        d["T2"] = tl >= 0.10 * n
        d["T3"] = tl >= 8 * p
        d["recurrent"] = d["T1"] and d["T2"] and d["T3"]
    d["tail_share"] = (d.get("tail", 0) / n) if n else 0.0
    dx = [fnum(r.get("dx_inf")) for r in raws]
    d["sum_dx_inf"] = sum(v for v in dx if v is not None)
    d["dx_present"] = sum(1 for v in dx if v is not None)
    d["gone"] = (not d["recurrent"]) and d["sum_dx_inf"] > 0
    return d


def slice_write(head, cols, lines, out_dir, cell, arm, k, kind, why, src):
    path = os.path.join(out_dir, "%s-%s-solve%d.csv" % (arm, cell, k))
    with open(path, "w") as fh:
        for h in head:
            fh.write(h + "\n")
        fh.write("# SLICE of this task's flat neutrality trace (POST-HOC read-out)\n")
        fh.write("# slice_cell=%s\n" % cell)
        fh.write("# slice_arm=%s\n" % arm)
        fh.write("# slice_solve=%d\n" % k)
        fh.write("# slice_kind=%s\n" % kind)
        fh.write("# slice_reason=%s\n" % why)
        fh.write("# slice_source=%s\n" % src)
        fh.write("# slice_rows=%d\n" % len(lines))
        fh.write(cols + "\n")
        for r in lines:
            fh.write(r + "\n")
    return path


def main():
    trace_dir, slice_dir, out_md = sys.argv[1], sys.argv[2], sys.argv[3]
    os.makedirs(slice_dir, exist_ok=True)
    md = open(out_md, "w")
    w = md.write
    w("# M7 W2 M4 — POST-HOC read-outs over the twelve NEUTRALITY traces\n\n")
    w("Generated by `wrappers/readouts_driver_m4.py`; **no solver ran here.**\n")
    w("Every figure is machine-written from this task's own flat traces, whose\n")
    w("sha256 are in `traces-m4/SHA256-traces-m4.txt`, and from the slices in\n")
    w("`traces-m4/`. The tail finder is `readouts_m4.py`'s, unedited.\n\n")
    w("**POST-HOC.** RULE.md §6 was pre-registered for §1.1's TEN cells and for\n")
    w("phase-3 legs that §8 stopped before they ran. It was never pre-registered\n")
    w("for §1.2's three neutrality cells. Nothing here is a verdict of the rule,\n")
    w("and RULE.md is not edited.\n\n")

    loaded, capped_union = {}, {}
    for cell in CELLS:
        capped_union[cell] = set()
        for arm in ARMS:
            src = os.path.join(trace_dir, "%s-%s.csv" % (arm, cell))
            head, cols, rows, hdr = read_flat(src)
            buckets = by_solve(rows)
            loaded[(arm, cell)] = (src, head, cols, buckets, hdr)
            for k, lines in buckets.items():
                if predicate(typed_rows(cols, lines))["recurrent"]:
                    capped_union[cell].add(k)

    # ---- the per-solve predicate table ----------------------------------
    w("## §6.2's predicate, per solve, per cell × arm\n\n")
    w("`N` passes; `p` the winning period (`-` = no exactly-periodic suffix at\n")
    w("any p ≤ 64); `|T|` the tail. `REC` = RECURRENT_TAIL (T1∧T2∧T3),\n")
    w("`GONE` = ¬REC ∧ Σ‖Δx‖∞>0.\n\n")
    w("**No minor-cap column is printed.** The flat trace carries ONE `max_iter`\n")
    w("in its header, and that value is not the cap every QP in the run used — the\n")
    w("four arms' own headers on these three cells read 770/770/770/1770,\n")
    w("1170×4 and 1380/1380/2340/2760 — so a per-solve `capped` column derived\n")
    w("from it would be wrong for every solve but the captured one. Solve LENGTH\n")
    w("is printed instead and nothing is inferred from it.\n\n")
    totals = {}
    for cell in CELLS:
        w("### %s  (minor cap = %s)\n\n" % (
            cell, loaded[("off", cell)][4].get("max_iter", "?")))
        w("| arm | solve | N | p | \\|T\\| | T/N | T1 | T2 | T3 | REC | Σ‖Δx‖∞ | GONE |\n")
        w("|---|---|---|---|---|---|---|---|---|---|---|---|\n")
        for arm in ARMS:
            src, head, cols, buckets, hdr = loaded[(arm, cell)]
            nrec = ngone = rec_minors = tot_minors = 0
            for k in sorted(buckets):
                raws = typed_rows(cols, buckets[k])
                d = predicate(raws)
                nrec += bool(d["recurrent"])
                ngone += bool(d["gone"])
                tot_minors += d["N"]
                if d["recurrent"]:
                    rec_minors += d["N"]
                w("| %s | %d | %d | %s | %d | %.4f | %s | %s | %s | **%s** | %.6g | %s |\n" % (
                    arm, k, d["N"],
                    d["p"] if d["p"] is not None else "-", d.get("tail", 0),
                    d["tail_share"], int(d["T1"]), int(d["T2"]), int(d["T3"]),
                    "REC" if d["recurrent"] else "-", d["sum_dx_inf"],
                    "GONE" if d["gone"] else "-"))
            totals[(arm, cell)] = (len(buckets), nrec, ngone, rec_minors,
                                   tot_minors)
        w("\n")

    w("## Totals — solves, RECURRENT_TAIL, RECURRENCE_GONE\n\n")
    w("`recurrent minors` is the sum of N over that arm's RECURRENT solves;\n")
    w("`all minors` the sum over every solve, which equals the row's own\n")
    w("`qp_minor_iters`.\n\n")
    w("| cell | arm | solves | RECURRENT | GONE | recurrent minors | all minors |"
      " recurrent share |\n|---|---|---|---|---|---|---|---|\n")
    for cell in CELLS:
        for arm in ARMS:
            t = totals[(arm, cell)]
            w("| %s | %s | %d | %d | %d | %d | %d | %.3f |\n"
              % (cell, arm, t[0], t[1], t[2], t[3], t[4],
                 (t[3] / t[4]) if t[4] else 0.0))
    w("\n")
    w("### The two questions the close-out asks, answered from the rows above\n\n")
    for cell in ("READING6", "ZAMB2-8"):
        o, e = totals[("off", cell)], totals[("E", cell)]
        w("* **%s.** OFF has %d RECURRENT solves carrying %d of its %d minors"
          " (%.1f%%); E has %d carrying %d of its %d (%.1f%%). Minors move"
          " %d → %d (%+d); minors inside RECURRENT solves move %d → %d"
          " (%+d); minors outside them move %d → %d (%+d).\n"
          % (cell, o[1], o[3], o[4], 100.0 * o[3] / o[4],
             e[1], e[3], e[4], 100.0 * e[3] / e[4],
             o[4], e[4], e[4] - o[4], o[3], e[3], e[3] - o[3],
             o[4] - o[3], e[4] - e[3], (e[4] - e[3]) - (o[4] - o[3])))
    w("\n**Read with care (POST-HOC):** a solve INDEX is comparable across two"
      " arms only up to the first solve at which the two walks diverge \u2014"
      " measured here as the lowest index whose record BLOCK is not"
      " byte-identical between the two arms:\n\n")
    for cell in CELLS:
        for arm in ("E", "L", "L+"):
            ob = loaded[("off", cell)][3]
            ab = loaded[(arm, cell)][3]
            div = None
            for k in sorted(set(ob) | set(ab)):
                if ob.get(k) != ab.get(k):
                    div = k
                    break
            w("* `%s` off vs %s: %s\n"
              % (cell, arm,
                 "no diverging solve \u2014 every record block is byte-identical"
                 if div is None else
                 ("first diverging solve index %d (off %s records, %s %s)"
                  % (div, len(ob.get(div, [])) if div in ob else "ABSENT",
                     arm,
                     len(ab.get(div, [])) if div in ab else "ABSENT"))))
    w("\nPast that point the same index is not the same subproblem, so only the"
      " AGGREGATE columns above are read, never a per-index pairing.\n\n")

    # ---- what the ROW gate cannot see: the per-minor trace ---------------
    extra = {}
    w("## The walk difference the ROW gate cannot see\n\n")
    w("The neutrality gate of RULE.md \u00a75.5 compares two ROWS. A row carries"
      " totals. Two walks can take different routes and arrive at identical"
      " totals, and then the gate reports them identical. The table below"
      " compares the two runs' PER-MINOR RECORDS instead, index by index,"
      " byte for byte, over the solves both runs have. It is POST-HOC and it"
      " decides nothing \u2014 but it is the only place the difference between"
      " \"inert\" and \"invisible at the row\" is visible.\n\n")
    w("| cell | arm | solves off / arm | solves with \u2265 1 differing record |"
      " differing records | first differing record |\n"
      "|---|---|---|---|---|---|\n")
    for cell in CELLS:
        ocols, ob = loaded[("off", cell)][2], loaded[("off", cell)][3]
        names = ocols.split(",")
        for arm in ("E", "L", "L+"):
            ab = loaded[(arm, cell)][3]
            nsolve = nrec = 0
            first_k = None
            first = "\u2014 (every shared record block is byte-identical)"
            got = False
            for k in sorted(set(ob) & set(ab)):
                diffs = [i for i, (x, y) in enumerate(zip(ob[k], ab[k]))
                         if x != y]
                if diffs or len(ob[k]) != len(ab[k]):
                    nsolve += 1
                    nrec += len(diffs) + abs(len(ob[k]) - len(ab[k]))
                if diffs and not got:
                    got = True
                    first_k = k
                    i = diffs[0]
                    xs, ys = ob[k][i].split(","), ab[k][i].split(",")
                    ff = [names[j] for j in range(min(len(xs), len(ys)))
                          if xs[j] != ys[j]]
                    first = ("solve %d, minor %s, first fields `%s`"
                             % (k, xs[1], "`, `".join(ff[:5])))
            w("| %s | %s | %d / %d | %d | %d | %s |\n"
              % (cell, arm, len(ob), len(ab), nsolve, nrec, first))
            if first_k is not None:
                extra.setdefault(cell, set()).add(first_k)
    w("\nThe solve named in the last column is SLICED into `traces-m4/` under"
      " every arm that has it, alongside the RECURRENT ones, so the first place"
      " two walks part can be read record by record.\n\n")

    # ---- the capped solves, under every arm, with §6.6's read-outs -------
    w("## §6.6's per-solve read-outs on the RECURRENT solves\n\n")
    w("The union of RECURRENT solve indices per cell is taken over all four\n")
    w("arms, and each such index is read under EVERY arm that has it, so a\n")
    w("recurrence one arm carries and another does not is visible from both\n")
    w("sides. An index that does not exist under an arm is reported ABSENT and\n")
    w("never silently dropped. The divergence caveat above applies to every\n")
    w("cross-arm reading of a single index.\n\n")
    made = []
    for cell in CELLS:
        capped_union[cell] |= extra.get(cell, set())
        ks = sorted(capped_union[cell])
        w("### %s — RECURRENT indices (union over arms) plus every first-divergence index above: %s\n\n" % (
            cell, ", ".join(str(k) for k in ks) if ks else "(none)"))
        for k in ks:
            for arm in ARMS:
                src, head, cols, buckets, hdr = loaded[(arm, cell)]
                if k not in buckets:
                    w("* arm `%s` solve %d: **ABSENT** — this arm's run has no "
                      "solve at that index (it ran %d solves).\n\n"
                      % (arm, k, len(buckets)))
                    continue
                p = slice_write(head, cols, buckets[k], slice_dir, cell, arm, k,
                                "RECURRENT_UNION",
                                "RECURRENT under at least one arm on this cell",
                                src)
                made.append(p)
                d = R.read_out(cell, p, "RECURRENT_UNION", k,
                               "arm=%s (POST-HOC)" % arm)
                w("#### arm `%s` — solve %d\n\n" % (arm, k))
                R.render(d, md)
    md.close()
    with open(os.path.join(slice_dir, "SLICES.txt"), "w") as fh:
        for p in sorted(made):
            fh.write(os.path.basename(p) + "\n")
    print("slices: %d" % len(made))
    print("read-outs: %s" % out_md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
