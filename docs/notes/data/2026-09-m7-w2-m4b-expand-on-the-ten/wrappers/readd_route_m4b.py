#!/usr/bin/env python3
"""M7 W2 M4b -- THE POST-HOC READ-OUT: by what ROUTE is the released bound re-added?

**POST-HOC, and labelled so wherever it is carried.**  `RULE.md` §6 pre-registers
M4 §§6.2-6.6 for this task's ten cells.  It does NOT pre-register this question,
which the settler asked after the chain had run.  It is answered ONLY from the
traces already taken; no solver runs here, no leg is re-run, and no verdict of
`verdict.txt` rests on it.

What it counts, per cell and per arm, over the WHOLE flat trace:

  * `drop->add pairs`      adjacent record pairs (drop pass, then add pass);
  * `re-add SAME identity` of those, the pairs whose ADD names exactly the
                           (block, index, side) the DROP released;
  * `add drop_route=none`  of those re-adds, the ones whose add record carries
                           `drop_route=none` -- i.e. the add came through the
                           ORDINARY blocking-constraint path of the ratio test,
                           not through a drop/re-pin route;
  * `alpha == 0`           re-adds whose recorded step is exactly zero;
  * `alpha == tau/|p_r|`   re-adds whose recorded step is EXACTLY the EXPAND
                           floor alpha_min = tau / |p_released| at this leg's
                           own printed `arm_tau` -- computed in IEEE double and
                           compared for BIT equality, never a tolerance;
  * `dx_inf > 0`           re-adds that actually moved the iterate;
  * `drop pass snapped`    drop passes whose `p_inf <= step_tol`.

Usage:  readd_route_m4b.py TAU OUT.md CELL=OFFTRACE,ETRACE  [CELL=...]
"""

import sys
from collections import OrderedDict

DROP = ("drop_dantzig", "drop_zero_probe", "drop_worst")
ADD = ("add", "add_shift", "ride_add")


def load(path):
    with open(path, errors="replace") as fh:
        lines = [l.rstrip("\n") for l in fh if not l.startswith("#")]
    cols = lines[0].split(",")
    return cols, [dict(zip(cols, l.split(","))) for l in lines[1:]]


def fnum(t):
    try:
        v = float(t)
    except (TypeError, ValueError):
        return None
    return None if v != v else v


def tally(path, tau):
    cols, rows = load(path)
    d = OrderedDict((k, 0) for k in (
        "records", "drop_passes", "drop_pass_snapped", "drop_add_pairs",
        "readd_same_identity", "readd_route_none", "readd_alpha_zero",
        "readd_alpha_is_expand_floor", "readd_dx_nonzero",
        "readd_alpha_other"))
    d["records"] = len(rows)
    for i, r in enumerate(rows):
        if r["action"] in DROP:
            d["drop_passes"] += 1
            pi, st = fnum(r["p_inf"]), fnum(r["step_tol"])
            if pi is not None and st is not None and pi <= st:
                d["drop_pass_snapped"] += 1
        if i + 1 >= len(rows):
            continue
        nxt = rows[i + 1]
        if r["action"] not in DROP or nxt["action"] not in ADD:
            continue
        if nxt["solve"] != r["solve"]:
            continue
        d["drop_add_pairs"] += 1
        rel = (r["released_block"], r["released_index"], r["released_side"])
        # A drop pass names what it released on the NEXT record (`post_drop`),
        # so the released identity of the pair is read off the ADD record's own
        # `released_*` fields, which the engine fills for the pass that follows
        # a drop.  Both are checked and must agree when both are present.
        rel2 = (nxt["released_block"], nxt["released_index"], nxt["released_side"])
        added = (nxt["block"], nxt["block_index"], nxt["block_side"])
        same = (added == rel) or (added == rel2)
        if not same:
            continue
        d["readd_same_identity"] += 1
        if nxt["drop_route"] == "none":
            d["readd_route_none"] += 1
        a = fnum(nxt["alpha"])
        pr = fnum(nxt["p_released"])
        dx = fnum(nxt["dx_inf"])
        if a is not None and a == 0.0:
            d["readd_alpha_zero"] += 1
        elif a is not None and pr not in (None, 0.0) and a == tau / abs(pr):
            d["readd_alpha_is_expand_floor"] += 1
        else:
            d["readd_alpha_other"] += 1
        if dx is not None and dx != 0.0:
            d["readd_dx_nonzero"] += 1
    return d


def main():
    tau = float(sys.argv[1])
    out = open(sys.argv[2], "w")
    w = out.write
    w("# M7 W2 M4b — **POST-HOC**: by what route is the released bound re-added?\n\n")
    w("Generated by `wrappers/readd_route_m4b.py`; **no solver ran here**, and\n")
    w("**this question is POST-HOC** — `RULE.md` §6 does not pre-register it.\n")
    w("Nothing in `verdict.txt` rests on it.\n\n")
    w("`tau` = %r, this leg's own printed `arm_tau`. `alpha == tau/|p_released|`\n"
      "is an IEEE-double BIT comparison, never a tolerance.\n\n" % tau)
    w("| cell | arm | records | drop passes | drop passes with ‖p‖∞ ≤ step_tol |"
      " drop→add pairs | add re-adds the SAME identity | of those,"
      " `drop_route=none` | α exactly 0 | α exactly the EXPAND floor |"
      " α other | Δx ≠ 0 |\n")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|\n")
    for spec in sys.argv[3:]:
        cell, paths = spec.split("=", 1)
        offp, ep = paths.split(",", 1)
        for arm, p in (("off", offp), ("E", ep)):
            d = tally(p, tau)
            w("| %s | %s | %d | %d | %d | %d | %d | %d | %d | %d | %d | %d |\n"
              % (cell, arm, d["records"], d["drop_passes"],
                 d["drop_pass_snapped"], d["drop_add_pairs"],
                 d["readd_same_identity"], d["readd_route_none"],
                 d["readd_alpha_zero"], d["readd_alpha_is_expand_floor"],
                 d["readd_alpha_other"], d["readd_dx_nonzero"]))
    out.close()
    print("written: %s" % sys.argv[2])
    return 0


if __name__ == "__main__":
    sys.exit(main())
